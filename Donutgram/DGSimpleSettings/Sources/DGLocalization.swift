import Foundation

/// Uses Telegram's selected language, including regional Russian packs, with English as the fallback.
public func dgLocalized(_ text: String, languageCode: String) -> String {
    let language = languageCode.lowercased().replacingOccurrences(of: "_", with: "-")
    if language == "ru" || language.hasPrefix("ru-") { return text }
    if let translated = dgEnglishStrings[text] { return translated }
    if text == text.uppercased(), let pair = dgEnglishStrings.first(where: { $0.key.uppercased() == text }) {
        return pair.value.uppercased()
    }
    // Only numeric labels are formatted here; editable text and usernames never pass through this function.
    for (suffix, replacement) in [(" сек.", " sec."), (" секунд", " seconds")] {
        if text.hasSuffix(suffix), Int(text.dropLast(suffix.count)) != nil {
            return String(text.dropLast(suffix.count)) + replacement
        }
    }
    return text
}

